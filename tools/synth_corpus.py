"""
synth_corpus — four weeks of somebody who does not exist, in the formats the pipeline reads.

The connectome pages are the best thing in this repo and they cannot be shown to anybody,
because every square on them is a diff of a private note. This writes a second vault so they
can be: `synthetic/sessions/<date>/` with a `microlite.md`, a sleep report, a ledger and an
`edit-me.md`, byte-compatible with what the real providers write. Point the rest of the repo at
it with `PETROGRAPH_OUT=synthetic` and every tool here — the waffle, `just connections`,
`just topics`, the connectome and its topic colouring — runs unchanged on data with nobody in
it. Nothing downstream was modified to make that work, and nothing downstream can tell.

WHAT REACHES THE MODEL THAT WRITES IT. `synthetic/profile.json`, which is sixty numbers;
`synthetic/style-guide.md`, which is those numbers written as instructions; and a list of
subjects, from `_story.py` under `--story` and from `_synth.SUBJECTS` otherwise. That is all. No
note, no title, no name, no sentence from the real vault is in this tool's inputs, and
`synth_profile.py`'s return type is what guarantees it
— see `baml_src/synth_profile.baml`. Every name in the output was invented by the first call
this tool makes and reused by all the rest.

FIVE STAGES, and the order is load-bearing.

  1. The roster. One call, and every later call chooses from it. A journal names the same dozen
     people for months, and recurrence is most of what separates a vault from four hundred
     unrelated paragraphs.
  2. The sources. The sleep report and the ledger, generated by arithmetic in `_synth_sources`,
     BEFORE a word of prose exists. Their figures are then handed to the writer, so a note about
     a bad night cites the night the ring recorded and a note about money cites the ledger's own
     number. That is what gives the letter something true to tie together — and a hunk-to-source
     arrow is a third of what the connectome draws.
  3. The threads. One call per subject, each planning a few notes and what happens in each
     of them week by week. A thread with a beat in week 1 and a beat in week 4 is a note the
     writer came back to, which is the inter-week arrow the page exists to show; asking for it
     up front is the only way to be sure there is one to find.
  4. The edits. One beat becomes one or two splices into the note's accumulated text. The tool
     picks where the change lands — appended, prepended, a rewritten passage, a deleted one —
     because that choice is what produces the profile's mix of added, mixed and removed hunks,
     and a model asked to choose would append every time.
  5. The diffs, by `difflib`. A model is never asked for a diff. It writes prose; this splices
     it in and diffs the before against the after. That matters more than it sounds: every id on
     the connectome is a position in one of these files, so the line counts in an `@@` header
     have to be arithmetic rather than something that looks like arithmetic.

There is no content filter on any of this and there deliberately is not one any more. What kept
the real vault out was never a word list — it is `synth_profile.py`'s return type, which has no
string field in it — and the word list that used to sit here only stopped the synthetic writer
from saying how they felt. A journal whose author may not be upset is a thinner test of the
connectome, not a safer one. See `_synth.py`.

The whole generation is cached call by call under `share/.baml-cache`, keyed by the prompts, the
profile, the style guide and the dates. Re-running to change how the files are laid out costs
nothing; changing a prompt correctly misses.

Usage:
    ./synth_corpus.py                     # write synthetic/sessions/ (uses the cache if warm)
    ./synth_corpus.py --dry-run           # the call count and what it would cost
    ./synth_corpus.py --weeks 2 --end 2026-02-13
    ./synth_corpus.py --no-cache          # generate a different vault from the same inputs
"""

