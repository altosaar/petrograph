def write_week(date: str, week_edits: list[dict], sources: dict, threshold: int,
               vault: int, seed: int, context: str, root: Path,
               held: str = "", after: str = "") -> Path:
    """One session directory: the diff, the two sources, and the file the run is started from.

    Named `mm-dd`, without the year — see `_synth.label` — after the day the read happened,
    which is `held` when that is not the week's Friday. The two source files take the same
    name, and those two are the only filenames from this folder a reader ever sees: the
    connectome draws a square for each of them and labels it with the filename. What is in them
    stays counted to the Friday, so the figures the notes quote are still the ones they carry.
    """
    stem = label(held or date)
    session = root / stem
    session.mkdir(parents=True, exist_ok=True)
    rng = random.Random(f"layout-{date}-{seed}")

    (session / "microlite.md").write_text(
        microlite_md(date, week_edits, threshold, vault, rng, held, after))
    oura_path = session / f"oura-{stem}.md"
    fin_path = session / f"finances-{stem}.md"
    oura_path.write_text(oura_md(sources["oura"]))
    fin_path.write_text(finances_md(sources["finances"]))
    (session / "edit-me.md").write_text(FRONT_MATTER.format(
        date=stem, diff=session.resolve() / "microlite.md",
        attachments=f"{fin_path.resolve()}, {oura_path.resolve()}",
        context=context.strip()))
    # The empty place the letter goes, exactly as `--new` would leave it, so `just synth-letters`
    # has something to overwrite and `just render` refuses until it has been.
    ensure_stub(session)
    return session


def report(root: Path, profile: dict) -> None:
    """Measure what was written with the loader the chart uses, beside what it was imitating."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from _hunks import load
    weeks = load(sorted(root.glob("*/microlite.md")))
    hunks = [h for w in weeks for h in w["hunks"]]
    if not hunks:
        return
    kinds = {k: sum(1 for h in hunks if h["kind"] == k) / len(hunks)
             for k in ("added", "mixed", "removed", "full")}
    diffs = [h for h in hunks if h["kind"] != "full"] or hunks
    med = sorted(h["chars"] for h in diffs)[len(diffs) // 2]
    print("\n            synthetic   real")
    print(f"  hunks/wk   {len(hunks) / len(weeks):>8.0f}   {profile['hunks_per_week']['median']:.0f}")
    print(f"  notes/wk   {sum(len(w['notes']) for w in weeks) / len(weeks):>8.0f}   "
          f"{profile['notes_per_week']['median']:.0f}")
    for k in ("added", "mixed", "removed", "full"):
        print(f"  {k:<9}  {kinds[k]:>8.0%}   {profile['kind_mix'][k]:.0%}")
    print(f"  chars med  {med:>8.0f}   {profile['hunk_chars']['median']:.0f}")


def assemble(plan: dict, dates: list[str], profile: dict, seed: int, out: Path,
             keep_letters: bool = True, threshold: int | None = None,
             keys: dict[str, str] | None = None,
             held: dict[str, str] | None = None) -> tuple[list[Path], int]:
    """The plan on disk: four session directories.

    Separate from `main` because `synth_links.py` writes the same vault from a plan it has added
    to, and two implementations of "what a session directory is" is the one thing this feature
    cannot afford — a note's content and its position in a file are what every id on the
    connectome resolves through.

    `keep_letters` is what makes it re-runnable. A fresh corpus replaces the vault whole, because
    half of one run and half of another share note titles without sharing their contents; a
    re-assembly after planting links must not throw away the letters that were written from it.
    """
    payees = plan["roster"]["organizations"] + plan["roster"]["places"]
    # Passed in by a caller that has changed the plan since. The threshold is a quantile over
    # every note's length, so adding a few lines to week four moves it, and a moved threshold
    # re-renders notes in EVERY week — flipping some between a diff and whole content, which
    # renumbers hunks the chart has already drawn arrows to. A caller planting into one week
    # holds the original so the other three come out byte-identical.
    if threshold is None:
        threshold = full_threshold(plan["edits"], profile["kind_mix"]["full"])
    # The reader's header counts the whole vault, not the week — a note nobody touched this week
    # is still a note in the folder it read.
    vault = len({e["note"] for e in plan["edits"]})

    # What the sleep report and the ledger are drawn from, when that is not the date they are
    # labelled with. `synth_vault` passes the reference calendar its notes were written against,
    # so the figures those notes quote stay true however far the corpus is shifted.
    keys = keys or {}
    saved = {}
    if out.exists():
        if keep_letters:
            saved = {p.parent.name: p.read_text()
                     for p in out.glob("*/lifelog-*.md") if p.is_file()}
        # Only the week directories. The rendered pages sit beside them, at the top of this
        # folder, and taking the whole tree took those with it — so regenerating the corpus
        # silently deleted the charts it exists to feed.
        for week in out.glob("*/"):
            if week.is_dir():
                shutil.rmtree(week)

    # The day each week was actually read, where that is not its Friday — `_synth.HELD`. Each
    # read is also the floor under the next week's edits.
    held = held or {}
    written, after = [], ""
    for date in dates:
        week_edits = [e for e in plan["edits"] if dates[e["week"] - 1] == date]
        key = keys.get(date, date)
        sources = {"oura": oura(date, seed, key), "finances": finances(date, seed, payees, key)}
        read = held.get(date, date)
        session = write_week(date, week_edits, sources, threshold, vault,
                             seed, plan["contexts"][date], out, held=read, after=after)
        after = read
        if (stem := label(read)) in saved:
            (session / f"{LIFELOG}-{stem}.md").write_text(saved[stem])
        written.append(session)

    return written, threshold


def main() -> None:
    ap = argparse.ArgumentParser(
        description="Four weeks of a vault that never existed, in the formats the pipeline reads.")
    ap.add_argument("--end", default=ANCHOR, help=f"Date of the newest week (default {ANCHOR}).")
    ap.add_argument("--weeks", type=int, default=WEEKS, help=f"How many weeks (default {WEEKS}).")
    ap.add_argument("--seed", type=int, default=7, help="Seed for every non-model choice.")
    ap.add_argument("--out", type=Path, default=SESSIONS, help="Where the sessions go.")
    ap.add_argument("--fresh", action="store_true",
                    help="Drop the letters too, back to stubs. Off by default: a letter is four "
                         "Opus calls and twenty minutes, and re-laying-out the notes is neither.")
    ap.add_argument("--no-cache", action="store_true", help="Generate again rather than reuse.")
    ap.add_argument("--dry-run", action="store_true", help="Say what it would cost. No call.")
    ap.add_argument("--story", metavar="NAME",
                    help="Plan each week as one act of a story instead of topic by topic. "
                         "`hamlet` is the one that ships (tools/_story.py). A vault with a plot "
                         "in it is a chart whose connections have a known answer.")
    ap.add_argument("--jobs", type=int, default=8,
                    help="Model calls in flight at once (default 8). Notes are independent of "
                         "each other and each carries its own random stream, so the corpus is "
                         "the same whatever this is set to.")
    ap.add_argument("--verbose", action="store_true", help="Name every note as it is written.")
    args = ap.parse_args()

    story = None
    if args.story:
        import importlib
        try:
            story = importlib.import_module("_story")
        except ImportError as exc:  # pragma: no cover - a setup failure, not a runtime one
            sys.exit(f"No story module ({exc}).")
        if story.NAME != args.story:
            sys.exit(f"--story {args.story}: the module here is {story.NAME}.")

    # Both are written by `just synth-profile` from the real vault, and both are gitignored: they
    # are measurements of a private notebook rather than anything synthetic, so a clone arrives
    # without them and has to measure its own. Named separately because a missing one is a
    # missing input, not a bug to read a traceback about.
    for needed in (PROFILE, STYLE_GUIDE):
        if not needed.is_file():
            sys.exit(f"No {needed.name} at {needed} — run: just synth-profile")
    profile = json.loads(PROFILE.read_text())
    style = STYLE_GUIDE.read_text()
    dates = week_dates(args.end, args.weeks)

    subjects = story.SUBJECTS if story is not None else SUBJECTS
    # The vault this repo actually ships is hand-written now — see tools/synth_vault.py. This
    # still works and is still worth having (it is what measured the shape, and a corpus with no
    # plot in it is the null hypothesis a plotted one has to beat), but running it replaces the
    # assembled sessions. synthetic/vault/ is the source and survives, so the way back is one
    # command; saying so here is cheaper than finding out.
    if (SYNTH_ROOT / "vault").is_dir():
        print("note     synthetic/vault/ exists — this overwrites the sessions assembled from "
              "it.\n         `just synth-vault` puts them back.\n")
    print(f"weeks    {len(dates)}: {', '.join(dates)}")
    print(f"subjects {len(subjects)}"
          + (f", from {story.NAME}" if story is not None else ", the generic set"))

    # Each call is cached on its own under share/.baml-cache, so this is what a cold run costs
    # and a warm one costs nothing. The estimate is the roster, one plan per topic, one context
    # per week, and one passage per note-week — which is what the profile's edit rate implies.
    est = 1 + len(subjects) + len(dates) + int(profile["hunks_per_week"]["median"] * len(dates))
    print(f"calls    up to ~{est}, each cached individually — a rerun pays only for what changed")

    if args.dry_run:
        print("\nDry run — no API call made, nothing billed.")
        return

