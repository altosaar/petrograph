# The four half-sentences `prompts/act-analysis.md` leaves for a person to finish by hand. The
# synthetic week answers them in its `## Week context`, which is the same place a real week's
# answers go — so the bundle carries the blanks and, a few lines later, the filled-in version of
# themselves, exactly as it does when somebody pastes the prompt into a chat window.
#
# Matched at the head of a paragraph and in order, without the ellipsis, because the ellipsis is
# the blank rather than punctuation the answer should keep: what comes back is "This upcoming
# week I need to find out who was on that roof", which is the opener filled in and reads like a
# person wrote it. `Emotionally I` is accepted alongside `Emotionally, I` for the same reason,
# and the match is case-insensitive because the style guide asks for mostly lower case and gets
# it — "this upcoming week i need to" is the voice working, not the format failing.
# Checked at all because a draft that quietly drops one leaves the read a question nobody asked.
OPENERS = (r"This upcoming week\b", r"Tomorrow\b", r"Today\b", r"Emotionally,? I\b")


def has_openers(text: str) -> bool:
    """Whether all four openers start a paragraph, in the order the prompt asks for."""
    found = 0
    for para in (p.strip() for p in re.split(r"\n\s*\n", text or "")):
        if found < len(OPENERS) and para and re.match(OPENERS[found], para, re.I):
            found += 1
    return found == len(OPENERS)

# How many notes each allowed topic is asked for. Sixteen topics at four notes apiece is
# sixty-four notes, which with the beat distribution below lands near the profile's forty-five
# notes and fifty-eight edits a week.
NOTES_PER_TOPIC = 4

# How many notes one act of a story leaves behind, when `--story` is on. Sized to land near the
# profile's forty-five notes a week; roughly half of each act's are files carried forward from an
# earlier act rather than new ones, which is where the arrows across the chart come from.
NOTES_PER_ACT = 40

# Where an edit lands, and how often. These weights are the only lever on the kind mix: material
# added at either end is an add-only hunk, a rewritten passage is a mixed one, a deleted passage
# is a remove-only one. Tuned against `--report`, which measures the corpus this produces with
# the same loader the chart uses and prints it beside the profile it was imitating.
OPS = {"append": 0.26, "prepend": 0.10, "revise": 0.56, "prune": 0.08}

# What share of notes already existed before the window opened. Most of a real vault does — a
# four-week diff of a years-old vault is mostly changes to notes that were already there — and
# without this every note's first appearance is a whole-file creation, which is an add-only hunk
# by definition. Sixty per cent of them starting with a body is what moves the corpus's kind mix
# off "everything is an addition" and onto the profile's.
PRE_HISTORY = 0.85
# Two splices in one week make one net diff with two `@@` blocks — which is where a
# hunks-per-note above 1 comes from, since the reader diffs a note's week as a whole.
TWO_OP_RATE = 0.28

# How much of a note the writer is shown when adding to it. Enough to continue it in the same
# voice and not repeat itself; a long note in full would crowd out the beat it is being asked for.
EXISTING_CHARS = 1500

# Any heading, for the hunk header's git-style section hint. A `##` inside a note is content.
HEADING = re.compile(r"^#{1,6}\s")
# The note's own title, and only that. Stripping every heading level instead is what emptied
# fifty-two passages that legitimately opened with a `## week of …` and turned their note-weeks
# into silent no-ops — the note stopped changing, so the reader stopped listing it.
TITLE = re.compile(r"^#\s")


def paragraphs(text: str) -> list[str]:
    """A note as blocks. A bullet list is one block, which is what makes a splice look human."""
    return [b for b in re.split(r"\n\s*\n", text.strip()) if b.strip()]


def splice(text: str, op: str, passage: str, rng: random.Random) -> str:
    """Put `passage` where `op` says, and return the note as it now stands."""
    blocks = paragraphs(text)
    if not blocks:
        return passage.strip()
    # A note that opens with a heading keeps it. Prepending above the title would be the one
    # thing no editor does.
    head = 1 if TITLE.match(blocks[0]) and len(blocks[0].splitlines()) == 1 else 0
    body = list(range(head, len(blocks)))
    if op == "prune":
        # No passage, and nothing to strip off one. Guarding this with the title rule below is
        # how a prune quietly became a no-op and the corpus lost every removal it had.
        if len(body) > 1:
            del blocks[rng.choice(body)]
        return "\n\n".join(blocks)
    if head:
        # Asked for a passage of a named note, the model writes the note's title again at the
        # top of it, every time. Told not to, it does it anyway about a third of the time — so
        # the title is taken off here instead, where it is not a matter of persuasion. Without
        # this a four-week note ends up with its own H1 stacked four deep, which is the first
        # thing anybody would notice in a diff.
        lines = passage.lstrip().splitlines()
        if lines and TITLE.match(lines[0]):
            passage = "\n".join(lines[1:]).lstrip()
    passage = passage.strip()
    if not passage:
        return text
    if op == "prepend":
        blocks.insert(head, passage)
    elif op == "revise" and body:
        blocks[rng.choice(body)] = passage
    else:
        blocks.append(passage)
    return "\n\n".join(blocks)


def choose_ops(text: str, rng: random.Random) -> list[str]:
    """Which splices this week's edit is made of. Empty note, one op: writing it."""
    if not text.strip():
        return ["create"]
    blocks = paragraphs(text)
    # The body is everything under the title, which is what an edit can actually touch — the
    # same count `splice` works from, so the two cannot disagree about what is possible.
    body = len(blocks) - (1 if TITLE.match(blocks[0]) and len(blocks[0].splitlines()) == 1 else 0)
    names, weights = zip(*OPS.items())
    if body < 1:
        # Nothing to revise around and nothing to spare; a short note grows before it changes.
        names, weights = ("append", "prepend"), (0.75, 0.25)
    elif body < 2:
        # One paragraph: it can be rewritten, but deleting it would empty the note.
        names, weights = ("append", "prepend", "revise"), (0.4, 0.16, 0.44)
    ops = [rng.choices(names, weights)[0]]
    if rng.random() < TWO_OP_RATE and body >= 2:
        second = rng.choices(names, weights)[0]
        if second != ops[0]:
            ops.append(second)
    return ops


